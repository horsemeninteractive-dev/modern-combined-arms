#!/usr/bin/env python3
"""Render the trailer's voiceover with the game's narrator chain.

The narrator assets in `public/audio/narrator` are generated by
`tools/narrator-voice/generate.py` running Kokoro-82M through a fixed processing
chain. The trailer uses the same model, the same voice family and the same
preset, so the trailer is read in a voice the game already has, rather than in
whatever a hosted TTS happened to return today.

Lines and placement live in `tools/trailer/narration.json`; the timeline is
resolved from clip lengths at render time, so this tool only has to produce one
file per line plus a manifest of durations.

Setup (the venv and model files the narrator tool already uses):
  python -m venv .dev/voice-venv
  .dev/voice-venv/Scripts/pip install -r tools/unit-voice/requirements.txt
  # model: tmp/kokoro/kokoro-v1.0.onnx and voices-v1.0.bin

Usage:
  .dev/voice-venv/Scripts/python tools/trailer/voice.py
  .dev/voice-venv/Scripts/python tools/trailer/voice.py --refresh
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import soundfile

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools" / "narrator-voice"))

from generate import (  # noqa: E402  (path set above)
    DEFAULT_LINES,
    DEFAULT_MODEL,
    DEFAULT_VOICES,
    SAMPLE_RATE,
    encode_mp3,
    measure,
    process,
    raw_path,
    synth,
)

DEFAULT_SCRIPT = Path(__file__).with_name("narration.json")
OUT_DIR = ROOT / "trailer" / "audio"
RAW_DIR = ROOT / "tmp" / "trailer-voice-raw"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--script", type=Path, default=DEFAULT_SCRIPT)
    parser.add_argument("--out", type=Path, default=OUT_DIR)
    parser.add_argument("--raw-dir", type=Path, default=RAW_DIR)
    parser.add_argument("--model", type=Path, default=DEFAULT_MODEL)
    parser.add_argument("--voices", type=Path, default=DEFAULT_VOICES)
    parser.add_argument("--refresh", action="store_true", help="re-synthesise cached speech")
    args = parser.parse_args()

    for path, label in ((args.model, "model"), (args.voices, "voices")):
        if not path.exists():
            print(f"missing Kokoro {label}: {path}", file=sys.stderr)
            return 2

    document = json.loads(args.script.read_text(encoding="utf-8"))
    presets = json.loads(DEFAULT_LINES.read_text(encoding="utf-8"))["presets"]
    preset_name = document.get("preset", "command")
    if preset_name not in presets:
        print(f"unknown preset {preset_name}", file=sys.stderr)
        return 2
    preset = presets[preset_name]
    voice = document["voice"]
    speed = float(document.get("speed", 1.0))

    from kokoro_onnx import Kokoro

    kokoro = Kokoro(str(args.model), str(args.voices))
    manifest = {"voice": voice, "preset": preset_name, "speed": speed, "lines": []}

    for line in document["lines"]:
        raw = raw_path(args.raw_dir, "trailer", line["id"], voice)
        if args.refresh or not raw.exists():
            synth(kokoro, line["text"], voice, speed, raw)
        samples, rate = soundfile.read(str(raw), dtype="float32", always_2d=False)
        if rate != SAMPLE_RATE:
            print(f"{line['id']}: {rate} Hz, expected {SAMPLE_RATE}", file=sys.stderr)
            return 3
        mixed = process(np.asarray(samples, dtype=np.float32), preset)
        target = args.out / f"vo-{line['id']}.mp3"
        encode_mp3(target, mixed)
        stats = measure(target)
        manifest["lines"].append(
            {
                "id": line["id"],
                "shot": line["shot"],
                "at": line["at"],
                "text": line["text"],
                "file": str(target.relative_to(ROOT)).replace("\\", "/"),
                "seconds": stats["seconds"],
                "peakDb": stats["peakDb"],
                "rmsDb": stats["rmsDb"],
            }
        )
        print(f"{line['id']}  {stats['seconds']:5.2f}s  peak {stats['peakDb']:6.2f} dB  {line['text']}")

    (args.out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    total = sum(line["seconds"] for line in manifest["lines"])
    print(f"\n{len(manifest['lines'])} line(s), {total:.2f}s of speech -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
