export const UNITS: Record<string, UnitDef> = Object.fromEntries(
  [...ROSTER, ...ALLIANCE_UNITS, ...NATIONAL_UNITS].map((u) => [u.id, u]),
);
export const UNIT_LIST = ROSTER;

/** Registered alliance platforms; excluded from the shared baseline. */
export const ALLIANCE_UNIT_LIST = ALLIANCE_UNITS;

/** Registered national variants; excluded from both alliance baselines. */
export const NATIONAL_UNIT_LIST = NATIONAL_UNITS;

/**
 * Canonical baseline slot for a unit, walking the whole `variantOf` chain.
 *
 * A national replacement of an alliance platform still reports the canonical
 * slot the production list and the AI name, so "slot → alliance platform →
 * national replacement" keeps one identity. A broken chain reports the queried
 * id rather than an unrelated ancestor.
 */
export function unitFamily(id: string): string {
  return resolveVariantChain(UNITS, id).root;
}

export function unitDef(id: string): UnitDef {
  const def = UNITS[id];
  if (!def) throw new Error(`Unknown unit definition: ${id}`);
  return def;
}
